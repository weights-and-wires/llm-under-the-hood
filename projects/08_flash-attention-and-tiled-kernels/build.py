import time

def bench(fn, q, k, v, repeats=10):
    for _ in range(3):  # warmup
        fn(q, k, v)
    torch.cuda.synchronize()
    t0 = time.perf_counter()
    for _ in range(repeats):
        fn(q, k, v)
    torch.cuda.synchronize()
    return (time.perf_counter() - t0) / repeats
