# === Step 11: Define the Loss ===

def loss_fn(model: 'MLP', xs: list, ys: list) -> tuple:
    preds = [model(x) for x in xs]
    loss = sum((pred - y)**2 for pred, y in zip(preds, ys))
    return loss, preds

